import numpy as np


def main():
    # 1. Створення одновимірного масиву з 200 випадкових чисел від -100 до 100.
    # Використовуємо np.random.randint (від -100 до 101, щоб 100 було включно)
    array = np.random.randint(-100, 101, size=200)

    # 2. Використовуючи маску, відфільтруйте всі додатні числа в масиві.
    mask_positive = array > 0
    positive_numbers = array[mask_positive]

    # 3. Заміна всіх від’ємних значень на нулі.
    # Створимо копію, щоб зберегти початковий масив (або можна змінювати одразу array)
    result_array = array.copy()
    result_array[result_array < 0] = 0

    # 4. Обчислення середнього значення отриманого масиву.
    mean_value = np.mean(result_array)

    # Виведення результатів для перевірки
    print("Оригінальний масив (перші 10 елементів):", array[:10])
    print(f"Кількість відфільтрованих додатних чисел: {len(positive_numbers)}")
    print("Масив після заміни від'ємних на нулі (перші 10 елементів):", result_array[:10])
    print(f"Середнє значення отриманого масиву: {mean_value:.2f}")


if __name__ == "__main__":
    main()